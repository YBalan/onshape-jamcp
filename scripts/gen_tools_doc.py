"""Generate docs/tools.md from the live MCP tool schemas.

uv run python scripts/gen_tools_doc.py           # rewrite docs/tools.md
uv run python scripts/gen_tools_doc.py --check   # exit 1 if the file is stale (used by CI/tests)
"""

import argparse
import asyncio
import sys
from pathlib import Path
from typing import Any

from onshape_jamcp.config import Settings
from onshape_jamcp.server import build_server

OUTPUT = Path(__file__).resolve().parent.parent / "docs" / "tools.md"

GROUPS: list[tuple[str, str, list[str]]] = [
    (
        "Server & diagnostics",
        "Know what the server is configured to do.",
        ["get_settings", "whoami"],
    ),
    (
        "Documents",
        "Find, create and organise documents and their tabs.",
        ["list_documents", "get_document", "create_document", "create_element"],
    ),
    (
        "Inspect",
        "Read-only views of a model: features, parts, measurements, faces/edges, assemblies.",
        [
            "list_features",
            "list_parts",
            "get_part_properties",
            "get_body_details",
            "get_assembly",
            "run_featurescript",
        ],
    ),
    (
        "Model",
        "Create and edit Part Studio geometry. Hidden entirely when `ONSHAPE_READ_ONLY=true`.",
        [
            "create_sketch",
            "extrude",
            "fillet",
            "chamfer",
            "update_feature",
            "delete_feature",
            "add_feature",
        ],
    ),
    (
        "Look & export",
        "Screenshots (with the token-saving review toggle) and file export.",
        ["capture_screenshot", "export_model"],
    ),
    ("Escape hatch", "Anything the dedicated tools do not cover.", ["onshape_api_request"]),
]


def type_of(schema: dict[str, Any], defs: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return repr(schema["const"])
    if "enum" in schema:
        return " | ".join(repr(v) for v in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts = [type_of(s, defs) for s in schema[key]]
            parts = [p for p in dict.fromkeys(parts) if p != "null"]
            return " | ".join(parts)
    kind = schema.get("type")
    if kind == "array":
        return f"array of {type_of(schema.get('items', {}), defs)}"
    return str(kind or "any")


def cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def render_shapes(defs: dict[str, Any]) -> list[str]:
    """Document the sketch shape types (they appear as $defs of create_sketch)."""
    out = [
        "**Shape types** (`type` selects one). Coordinates are `[x, y]` in the sketch plane,",
        'in the configured length unit, or strings with a unit such as `"1.5 in"`:',
        "",
    ]
    for shape in defs.values():
        out += [
            f"- **`{shape['properties']['type']['const']}`** - "
            + " ".join(shape.get("description", "").split()),
            "",
            "  | Field | Type | Required | Description |",
            "  |---|---|---|---|",
        ]
        required = set(shape.get("required", []))
        for fname, fschema in shape["properties"].items():
            if fname == "type":
                continue
            desc = fschema.get("description", "")
            if "default" in fschema and fschema["default"] is not None:
                desc = f"{desc} Default: `{fschema['default']}`.".strip()
            out.append(
                f"  | `{fname}` | {cell(type_of(fschema, defs))} | "
                f"{'yes' if fname in required else 'no'} | {cell(desc)} |"
            )
        out.append("")
    return out


def render(tools: list[Any]) -> str:
    by_name = {t.name: t for t in tools}
    listed = [n for _, _, names in GROUPS for n in names]
    missing = sorted(set(by_name) - set(listed))
    if missing:
        raise SystemExit(f"Tools missing from GROUPS in gen_tools_doc.py: {missing}")

    out = [
        "# Tool reference",
        "",
        "<!-- GENERATED by scripts/gen_tools_doc.py from the live tool schemas - do not edit. -->",
        "",
        f"{len(tools)} tools. Lengths are in the configured unit (**millimeters by default**, "
        "inches with `ONSHAPE_UNITS=imperial`); angles are degrees. See "
        "[configuration](configuration.md).",
        "",
        "Legend: 🔍 read-only · ✏️ modifies a document · ⚠️ destructive.",
        "",
    ]
    for title, blurb, names in GROUPS:
        out += [f"## {title}", "", blurb, ""]
        for name in names:
            tool = by_name.get(name)
            if tool is None:
                continue
            ann = tool.annotations
            badge = "🔍" if ann and ann.read_only_hint else "✏️"
            if ann and ann.destructive_hint:
                badge = "✏️ ⚠️"
            out += [f"### `{name}` {badge}", "", " ".join(tool.description.split()), ""]
            schema = tool.input_schema
            props = schema.get("properties", {})
            required = set(schema.get("required", []))
            if props:
                out += ["| Parameter | Type | Required | Description |", "|---|---|---|---|"]
                for pname, pschema in props.items():
                    desc = pschema.get("description", "")
                    default = pschema.get("default", None)
                    if "default" in pschema and default is not None:
                        desc = f"{desc} Default: `{default}`.".strip()
                    out.append(
                        f"| `{pname}` | {cell(type_of(pschema, schema.get('$defs', {})))} | "
                        f"{'yes' if pname in required else 'no'} | {cell(desc)} |"
                    )
                out.append("")
                if name == "create_sketch":
                    out += render_shapes(schema.get("$defs", {}))
            else:
                out += ["_No parameters._", ""]
    return "\n".join(out).rstrip() + "\n"


async def generate() -> str:
    server = build_server(Settings.from_env({}))
    return render(await server.list_tools())


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if docs/tools.md is stale")
    args = parser.parse_args()
    text = asyncio.run(generate())
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("docs/tools.md is out of date. Run: uv run python scripts/gen_tools_doc.py")
            sys.exit(1)
        print("docs/tools.md is up to date.")
        return
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
